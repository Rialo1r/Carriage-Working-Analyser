-- Fresh Phase 1 planner schema. Never apply to the legacy analyser database.

CREATE TABLE "HistoricalPeriod" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "name" TEXT NOT NULL,
  "startDate" DATE,
  "endDate" DATE,
  "notes" TEXT NOT NULL DEFAULT ''
);

CREATE TABLE "PublishedDiagram" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "periodId" UUID NOT NULL,
  "number" TEXT NOT NULL,
  "description" TEXT NOT NULL DEFAULT '',
  "revision" INTEGER NOT NULL DEFAULT 1,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "Station" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "name" TEXT NOT NULL,
  "notes" TEXT NOT NULL DEFAULT ''
);

CREATE TABLE "CarriageType" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "name" TEXT NOT NULL,
  "code" TEXT,
  "notes" TEXT NOT NULL DEFAULT ''
);

CREATE TABLE "Formation" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "name" TEXT NOT NULL,
  "completeness" TEXT NOT NULL DEFAULT 'Unknown',
  "notes" TEXT NOT NULL DEFAULT '',
  "revision" INTEGER NOT NULL DEFAULT 1,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "FormationMember" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "formationId" UUID NOT NULL,
  "typeId" UUID,
  "quantity" INTEGER,
  "position" INTEGER,
  "vehicleNumber" TEXT,
  "notes" TEXT NOT NULL DEFAULT ''
);

CREATE TABLE "WorkingDefinition" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "diagramId" UUID NOT NULL,
  "label" TEXT NOT NULL DEFAULT '',
  "startStationId" UUID,
  "finishStationId" UUID,
  "startMinutes" INTEGER,
  "finishMinutes" INTEGER,
  "startDayOffset" INTEGER NOT NULL DEFAULT 0,
  "finishDayOffset" INTEGER NOT NULL DEFAULT 0,
  "formationId" UUID,
  "routeText" TEXT NOT NULL DEFAULT '',
  "notes" TEXT NOT NULL DEFAULT '',
  "exclusive" BOOLEAN NOT NULL DEFAULT true,
  "revision" INTEGER NOT NULL DEFAULT 1,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL
);

CREATE TABLE "OperatingCalendar" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "workingId" UUID NOT NULL UNIQUE,
  "weekdays" INTEGER[] NOT NULL,
  "validFrom" DATE,
  "validTo" DATE,
  "notes" TEXT NOT NULL DEFAULT ''
);

CREATE TABLE "CalendarException" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "calendarId" UUID NOT NULL,
  "date" DATE NOT NULL,
  "operates" BOOLEAN NOT NULL,
  "notes" TEXT NOT NULL,
  UNIQUE ("calendarId", "date")
);

CREATE TABLE "RouteCall" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "workingId" UUID NOT NULL,
  "stationId" UUID NOT NULL,
  "sequence" INTEGER NOT NULL,
  "notes" TEXT NOT NULL DEFAULT '',
  UNIQUE ("workingId", "sequence")
);

CREATE TABLE "SpecialInstruction" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "workingId" UUID NOT NULL,
  "weekdays" INTEGER[] NOT NULL,
  "text" TEXT NOT NULL
);

CREATE TABLE "FormationVariation" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "workingId" UUID NOT NULL,
  "weekday" INTEGER NOT NULL,
  "formationId" UUID,
  "notes" TEXT NOT NULL,
  UNIQUE ("workingId", "weekday")
);

CREATE TABLE "FormationChange" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "workingId" UUID NOT NULL,
  "weekdays" INTEGER[] NOT NULL,
  "action" TEXT NOT NULL,
  "stage" TEXT NOT NULL,
  "typeId" UUID,
  "quantity" INTEGER,
  "notes" TEXT NOT NULL
);

CREATE TABLE "SourceReference" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "workingId" UUID NOT NULL,
  "title" TEXT NOT NULL,
  "sourceDate" TEXT,
  "page" TEXT,
  "notes" TEXT NOT NULL DEFAULT ''
);

CREATE TABLE "NextWorkingReference" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "workingId" UUID NOT NULL,
  "weekday" INTEGER NOT NULL,
  "kind" TEXT NOT NULL,
  "targetWorkingId" UUID,
  "enteredNumber" TEXT,
  "offsetDays" INTEGER,
  "targetWeekday" INTEGER,
  "targetDate" DATE,
  "notes" TEXT NOT NULL DEFAULT '',
  UNIQUE ("workingId", "weekday")
);

CREATE TABLE "WorkingOccurrence" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "workingId" UUID NOT NULL,
  "date" DATE NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE ("workingId", "date")
);

CREATE TABLE "OccurrenceReference" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "fromId" UUID NOT NULL UNIQUE,
  "toId" UUID,
  "kind" TEXT NOT NULL,
  "note" TEXT NOT NULL
);

CREATE TABLE "PhysicalSet" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "serial" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
  "label" TEXT NOT NULL DEFAULT '',
  "notes" TEXT NOT NULL DEFAULT '',
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "RotationAssignment" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "physicalSetId" UUID NOT NULL,
  "occurrenceId" UUID NOT NULL,
  "exclusiveKey" UUID UNIQUE,
  "active" BOOLEAN NOT NULL DEFAULT true,
  "notes" TEXT NOT NULL,
  "definitionRevision" INTEGER NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE ("physicalSetId", "occurrenceId")
);

CREATE TABLE "ResearchNote" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "workingId" UUID NOT NULL,
  "text" TEXT NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "AuditEvent" (
  "id" UUID NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
  "entityId" UUID NOT NULL,
  "entityType" TEXT NOT NULL,
  "action" TEXT NOT NULL,
  "reason" TEXT NOT NULL,
  "before" JSONB,
  "after" JSONB,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

